"""Report writers: findings CSV, Markdown and simple HTML."""

from __future__ import annotations

import html
from datetime import datetime
from pathlib import Path

import pandas as pd

from . import __version__
from .common import FINDING_COLUMNS, Finding
from .price_adjustment import (SUPPORTING_DOCUMENTS, PriceAdjustmentResult, describe_deadline,
                               render_notice_letter)
from .rules import RULES

SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2}


def findings_frame(findings: list[Finding]) -> pd.DataFrame:
    rows = [f.to_dict() for f in findings]
    frame = pd.DataFrame(rows, columns=FINDING_COLUMNS)
    if frame.empty:
        return frame
    frame["_sev"] = frame["severity"].map(SEVERITY_ORDER)
    frame = frame.sort_values(["_sev", "rule_id", "employee_id", "line_id"]).drop(columns="_sev")
    return frame.reset_index(drop=True)


def summarize(frame: pd.DataFrame) -> dict:
    def total(direction: str, column: str = "difference") -> float:
        sub = frame[frame["direction"] == direction][column].dropna()
        return round(float(sub.abs().sum()), 2)

    return {
        "findings": len(frame),
        "high": int((frame["severity"] == "high").sum()),
        "medium": int((frame["severity"] == "medium").sum()),
        "low": int((frame["severity"] == "low").sum()),
        "overbilled_count": int((frame["direction"] == "overbilled").sum()),
        "overbilled_amount": total("overbilled"),
        "underbilled_count": int((frame["direction"] == "underbilled").sum()),
        "underbilled_amount": total("underbilled"),
        "underpaid_worker_count": int((frame["direction"] == "underpaid_worker").sum()),
        "owed_to_workers": round(float(frame["amount_owed_to_worker"].dropna().sum()), 2),
    }


def _billing_report(frame: pd.DataFrame) -> bool:
    return frame.empty or (frame["module"] == "invoice").any()


def _money(value) -> str:
    if value is None or pd.isna(value):
        return ""
    return f"{value:,.2f}"


def _md_escape(text: str) -> str:
    return str(text).replace("|", "\\|")


def render_markdown(title: str, frame: pd.DataFrame, source: str) -> str:
    s = summarize(frame)
    out = [
        f"# {title}",
        "",
        f"Generated by labor-charge-verifier {__version__} on "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M')} from `{source}`.",
        "",
        "Every finding is a lead for a person to review, not a conclusion. Each row "
        "names the rule that produced it; see docs/rules-catalog.md for what each rule "
        "checks and why.",
        "",
        "## Summary",
        "",
        "| Measure | Count | Amount (USD) |",
        "|---|---:|---:|",
        f"| Findings (high / medium / low) | {s['findings']} ({s['high']} / {s['medium']} / {s['low']}) | |",
    ]
    if _billing_report(frame):
        out += [
            f"| Overbilled: charges the records do not support | {s['overbilled_count']} | {s['overbilled_amount']:,.2f} |",
            f"| Underbilled: supported work left off the invoice | {s['underbilled_count']} | {s['underbilled_amount']:,.2f} |",
        ]
    out += [
        f"| Workers paid less than required or recorded | {s['underpaid_worker_count']} | {s['owed_to_workers']:,.2f} |",
        "",
        "## Findings",
        "",
    ]
    if frame.empty:
        out.append("No findings.")
    else:
        out += [
            "| # | Rule | Severity | Direction | Employee | Post | Line | Period | Billed | Expected | Difference | Owed to worker | Description |",
            "|---:|---|---|---|---|---|---|---|---:|---:|---:|---:|---|",
        ]
        for n, row in frame.iterrows():
            out.append(
                f"| {n + 1} | {row['rule_id']} | {row['severity']} | {row['direction']} | "
                f"{row['employee_id']} | {row['post_id']} | {row['line_id']} | "
                f"{row['period']} | {_money(row['billed_amount'])} | "
                f"{_money(row['expected_amount'])} | {_money(row['difference'])} | "
                f"{_money(row['amount_owed_to_worker'])} | {_md_escape(row['description'])} |")
    out += ["", "## Rules applied", ""]
    modules = set(frame["module"]) if not frame.empty else set()
    for rule in RULES.values():
        if rule.module in modules:
            out.append(f"- **{rule.rule_id}** {rule.title}. Basis: {rule.basis}")
    out.append("")
    return "\n".join(out)


HTML_STYLE = """
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:2rem;color:#1b1b1b;max-width:1400px}
table{border-collapse:collapse;margin:1rem 0;font-size:.85rem}
th,td{border:1px solid #c9c9c9;padding:.35rem .5rem;vertical-align:top;text-align:left}
th{background:#f0f0f0}
td.num{text-align:right;white-space:nowrap}
.high{color:#8a1c1c;font-weight:600}.medium{color:#7a5200}.low{color:#3d3d3d}
.note{color:#555;font-size:.9rem}
"""


def render_html(title: str, frame: pd.DataFrame, source: str) -> str:
    s = summarize(frame)
    esc = html.escape
    parts = [
        "<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>",
        f"<title>{esc(title)}</title><style>{HTML_STYLE}</style></head><body>",
        f"<h1>{esc(title)}</h1>",
        f"<p class='note'>Generated by labor-charge-verifier {__version__} on "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M')} from <code>{esc(source)}</code>. "
        "Every finding is a lead for a person to review, not a conclusion.</p>",
        "<h2>Summary</h2><table><tr><th>Measure</th><th>Count</th><th>Amount (USD)</th></tr>",
        f"<tr><td>Findings (high / medium / low)</td><td class='num'>{s['findings']} "
        f"({s['high']} / {s['medium']} / {s['low']})</td><td></td></tr>",
        (f"<tr><td>Overbilled</td><td class='num'>{s['overbilled_count']}</td>"
         f"<td class='num'>{s['overbilled_amount']:,.2f}</td></tr>"
         f"<tr><td>Underbilled</td><td class='num'>{s['underbilled_count']}</td>"
         f"<td class='num'>{s['underbilled_amount']:,.2f}</td></tr>")
        if _billing_report(frame) else "",
        f"<tr><td>Owed to workers</td><td class='num'>{s['underpaid_worker_count']}</td>"
        f"<td class='num'>{s['owed_to_workers']:,.2f}</td></tr></table>",
        "<h2>Findings</h2>",
    ]
    if frame.empty:
        parts.append("<p>No findings.</p>")
    else:
        headers = ["#", "Rule", "Severity", "Direction", "Employee", "Post", "Line",
                   "Period", "Billed", "Expected", "Difference", "Owed to worker",
                   "Description"]
        parts.append("<table><tr>" + "".join(f"<th>{h}</th>" for h in headers) + "</tr>")
        for n, row in frame.iterrows():
            cells = [
                f"<td class='num'>{n + 1}</td>",
                f"<td>{esc(row['rule_id'])}</td>",
                f"<td class='{esc(row['severity'])}'>{esc(row['severity'])}</td>",
                f"<td>{esc(row['direction'])}</td>",
                f"<td>{esc(str(row['employee_id']))}</td>",
                f"<td>{esc(str(row['post_id']))}</td>",
                f"<td>{esc(str(row['line_id']))}</td>",
                f"<td>{esc(str(row['period']))}</td>",
            ]
            for column in ("billed_amount", "expected_amount", "difference",
                           "amount_owed_to_worker"):
                cells.append(f"<td class='num'>{_money(row[column])}</td>")
            cells.append(f"<td>{esc(row['description'])}</td>")
            parts.append("<tr>" + "".join(cells) + "</tr>")
        parts.append("</table>")
    parts.append("</body></html>")
    return "\n".join(parts)


def write_findings_report(findings: list[Finding], out_dir: str | Path, stem: str,
                          title: str, source: str) -> dict[str, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    frame = findings_frame(findings)
    paths = {
        "csv": out_dir / f"{stem}_findings.csv",
        "md": out_dir / f"{stem}_report.md",
        "html": out_dir / f"{stem}_report.html",
    }
    frame.to_csv(paths["csv"], index=False)
    paths["md"].write_text(render_markdown(title, frame, source), encoding="utf-8")
    paths["html"].write_text(render_html(title, frame, source), encoding="utf-8")
    return paths


def write_price_adjustment_outputs(result: PriceAdjustmentResult, out_dir: str | Path,
                                   source: str) -> dict[str, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {
        "csv": out_dir / "price_adjustment_worksheet.csv",
        "letter": out_dir / "price_adjustment_notice_DRAFT.md",
        "documents": out_dir / "price_adjustment_supporting_documents.md",
        "summary": out_dir / "price_adjustment_summary.md",
    }
    result.worksheet.to_csv(paths["csv"], index=False)
    paths["letter"].write_text(render_notice_letter(result), encoding="utf-8")
    docs = ["# Supporting records to attach and keep", "",
            "FAR 52.222-43(f) asks for supporting data, including payroll records. "
            "Paragraph (g) gives the contracting officer access to directly pertinent "
            "records until 3 years after final payment. Keep these together:", ""]
    docs += [f"- [ ] {d}" for d in SUPPORTING_DOCUMENTS]
    paths["documents"].write_text("\n".join(docs) + "\n", encoding="utf-8")

    summary = [
        "# FAR 52.222-43 price adjustment worksheet - summary", "",
        f"Generated by labor-charge-verifier {__version__} from `{source}`.", "",
        "| Occupation | Allowable wage increase / hour | Allowable H&W increase / hour | "
        "Hours | Wage | H&W | Taxes and insurance | Total | Notes |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for _, row in result.worksheet.iterrows():
        summary.append(
            f"| {row['occupation_title']} ({row['occupation_code']}) | "
            f"{row['allowable_wage_increase_per_hour']:,.2f} | "
            f"{row['allowable_hw_increase_per_hour']:,.2f} | {row['hours']:,.0f} | "
            f"{row['wage_increase_amount']:,.2f} | {row['hw_increase_amount']:,.2f} | "
            f"{row['payroll_tax_and_insurance_amount']:,.2f} | "
            f"{row['total_adjustment']:,.2f} | {_md_escape(row['notes'])} |")
    summary += [
        "", f"**Total adjustment claimed: {result.total_adjustment:,.2f}**", "",
        f"Combined payroll tax and insurance rate applied: "
        f"{result.tax_rate_total * 100:.2f}% (from the configuration file).", "",
        "No overhead, G&A or profit is included (FAR 52.222-43(e)).", "",
        "This worksheet computes increases. Decreases must also be reported to the "
        "contracting officer promptly (FAR 52.222-43(f)).", "",
        "## Notice deadline (FAR 52.222-43(f))", "",
    ]
    for d in result.deadlines:
        summary.append(
            f"- WD received {d['wd_received_date']}: notice due by **{d['deadline']}**; "
            f"status: **{describe_deadline(d)}**.")
    if result.warnings:
        summary += ["", "## Warnings", ""] + [f"- {w}" for w in result.warnings]
    summary.append("")
    paths["summary"].write_text("\n".join(summary), encoding="utf-8")
    return paths
